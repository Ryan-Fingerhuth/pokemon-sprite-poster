// Extract each APNG's default image without altering the original sprite.
const fs = require('fs');
const path = require('path');
const assets = path.join(__dirname, '../src/assets');
const animated = [];
function visit(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === 'sprite-stills') continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) { visit(file); continue; }
    if (!entry.name.endsWith('.png')) continue;
    const data = fs.readFileSync(file);
    const chunks = [data.subarray(0, 8)];
    let isAnimated = false;
    for (let offset = 8; offset < data.length;) {
      const length = data.readUInt32BE(offset);
      const type = data.toString('ascii', offset + 4, offset + 8);
      const end = offset + length + 12;
      if (type === 'acTL') isAnimated = true;
      if (!['acTL', 'fcTL', 'fdAT'].includes(type)) chunks.push(data.subarray(offset, end));
      offset = end;
    }
    if (!isAnimated) continue;
    const relative = path.relative(assets, file).split(path.sep).join('/');
    const output = path.join(assets, 'sprite-stills', relative);
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, Buffer.concat(chunks));
    animated.push('assets/' + relative);
  }
}
visit(assets);
fs.writeFileSync(path.join(__dirname, '../src/app/@models/animated-sprites.ts'),
  '// Generated by scripts/generate-sprite-stills.cjs.\nexport const animatedSpritePaths = new Set<string>(' + JSON.stringify(animated.sort()) + ');\n');
console.log(`Generated ${animated.length} still sprite previews.`);
